"""Embed a .pte as a 16-byte-aligned flash array.

ExecuTorch's Program::load requires the program data 8-byte aligned
(kMinimumAlignment); ESP-IDF's EMBED_FILES only guarantees 4, so each
board's link layout decides whether the runner boots. The ESP-NN
delegate needs 16: its constants sit at a 16-multiple offset within
the blob, and an 8-but-not-16 base makes the runtime copy the whole
blob to PSRAM. This emits a const array with the alignment instead.
Usage:

    embed_pte.py <model.pte> <out-dir> <symbol>

writes <out-dir>/<symbol>.c and <out-dir>/<symbol>.h.
"""

import sys


def main() -> None:
    src, outdir, name = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(src, "rb") as f:
        data = f.read()
    rows = [
        ", ".join("0x%02x" % b for b in data[i : i + 16])
        for i in range(0, len(data), 16)
    ]
    body = ",\n    ".join(rows)
    with open("%s/%s.c" % (outdir, name), "w") as f:
        f.write(
            "// Generated by tools/embed_pte.py from %s - do not edit.\n"
            "#include <stddef.h>\n"
            "#include <stdint.h>\n"
            "__attribute__((aligned(16)))\n"
            "const uint8_t %s_start[%d] = {\n    %s\n};\n"
            "const size_t %s_len = %d;\n"
            % (src, name, len(data), body, name, len(data))
        )
    with open("%s/%s.h" % (outdir, name), "w") as f:
        f.write(
            "// Generated by tools/embed_pte.py - do not edit.\n"
            "#pragma once\n"
            "#include <stddef.h>\n"
            "#include <stdint.h>\n"
            "extern const uint8_t %s_start[];\n"
            "extern const size_t %s_len;\n" % (name, name)
        )


main()
